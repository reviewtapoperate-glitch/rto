-- RTO business discovery, attribution and customer access recovery.
-- Additive migration: preserve all existing business, customer and event records.
alter table public.customers
  add column if not exists booking_enabled boolean not null default true;

alter table public.page_events
  add column if not exists source text not null default 'unknown',
  add column if not exists referrer text;

create index if not exists page_events_slug_source_created_at_idx
  on public.page_events (slug, source, created_at desc);
create index if not exists page_events_created_at_idx
  on public.page_events (created_at desc);

create table if not exists public.access_code_reset_requests (
  id bigint generated by default as identity primary key,
  member_id uuid references public.members(id) on delete set null,
  member_name text not null,
  phone text not null,
  status text not null default 'pending' check (status in ('pending','resolved','rejected')),
  created_at timestamptz not null default now(),
  resolved_at timestamptz
);

create index if not exists access_code_reset_requests_status_created_idx
  on public.access_code_reset_requests (status, created_at asc);

alter table public.access_code_reset_requests enable row level security;
revoke all on table public.access_code_reset_requests from public, anon, authenticated;
grant all on table public.access_code_reset_requests to service_role;
grant usage, select on sequence public.access_code_reset_requests_id_seq to service_role;

-- All application access goes through the server API using the service role.
-- No browser role receives direct access to this reset-request table.
